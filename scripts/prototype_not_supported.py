#!/usr/bin/env python3
"""The prototype's fixed "not supported" answers (1235) for tolerance T1 of the result comparator.

The comparator (tools/ab/src/compare.rs) judges a 1235 from tidb-rs as `unsupported` only when it
is a boundary stub's answer (`blocked-by:<block>`) or one of the prototype's own fixed answers
listed in tools/ab/prototype-not-supported.txt (docs/testing/tolerances.toml, T1). Any other 1235
is a normal error: a ported Go branch returning ErrNotSupportedYet where Go answers is a mismatch.

This script extracts the list from the prototype's sources (string literals passed to
`not_supported(..)` / `unsupported(..)` / `Unsupported(..)` in crates/poc, crates/sql,
crates/mysql-protocol, crates/distsql); `{..}` placeholders become `.*`.

    scripts/prototype_not_supported.py           rewrite the list
    scripts/prototype_not_supported.py --check   fail if the list is stale (CI)
"""

import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tools", "ab", "prototype-not-supported.txt")
DIRS = ["crates/poc", "crates/sql", "crates/mysql-protocol", "crates/distsql"]
CALL = re.compile(r'\b(?:not_supported|unsupported|Unsupported)\(\s*(?:&?format!\(\s*)?"((?:[^"\\]|\\.)*)"', re.S)
# The router's own 1235 for a prepared statement only the new stack can run (crates/poc/session).
EXTRA = [r"this prepared statement on the PoC, and the new stack cannot run it now \(.*\)"]
HEADER = """\
# Generated by scripts/prototype_not_supported.py; do not edit. One regex per line: the text
# inside `This version of TiDB doesn't yet support '...'` of the prototype's fixed answers
# (tolerance T1, docs/testing/tolerances.toml).
"""


def literal(s):
    s = re.sub(r"\\\n\s*", "", s)  # Rust string continuation
    s = s.replace('\\"', '"').replace("\\\\", "\\")
    return s


def escape(s):
    """Escapes regex metacharacters only (the Rust regex crate rejects escaped spaces)."""
    return re.sub(r"([\\.+*?()|\[\]{}^$#&~-])", r"\\\1", s)


def pattern(text):
    parts = re.split(r"\{[^{}]*\}", text.replace("{{", "\x00").replace("}}", "\x01"))
    out = ".*".join(escape(p) for p in parts)
    return out.replace("\x00", r"\{").replace("\x01", r"\}")


def generate():
    pats = set(EXTRA)
    for d in DIRS:
        for f in glob.glob(os.path.join(ROOT, d, "**", "*.rs"), recursive=True):
            rel = os.path.relpath(f, ROOT)
            if "/tests/" in rel or rel.endswith("tests.rs"):
                continue
            src = open(f, encoding="utf-8").read()
            # Drop #[cfg(test)] modules (test-only answers).
            src = src.split("#[cfg(test)]\nmod tests")[0]
            for m in CALL.finditer(src):
                pats.add(pattern(literal(m.group(1))))
    return HEADER + "".join(p + "\n" for p in sorted(pats))


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if old != text:
            sys.exit(f"{os.path.relpath(OUT, ROOT)} is stale: run scripts/prototype_not_supported.py")
        print("prototype-not-supported.txt up to date")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"{os.path.relpath(OUT, ROOT)}: {text.count(chr(10)) - HEADER.count(chr(10))} patterns")


if __name__ == "__main__":
    main()
