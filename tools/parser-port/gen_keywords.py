#!/usr/bin/env python3
"""Extract keyword tables from TiDB misc.go into crates/parser/src/keywords_gen.rs.

Usage: python3 -I tools/parser-port/gen_keywords.py <misc.go> <out.rs>
(normally run through tools/parser-port/regen.sh)
Tables: tokenMap, btFuncTokenMap (only keywords when followed by '('),
windowFuncTokenMap (only when window functions are enabled), aliases, hintedTokens.
"""
import os
import re
import sys

SOURCE = os.environ.get("PARSER_PORT_SOURCE", "TiDB (unknown commit)")


def go_map(src, name):
    m = re.search(r"var %s = map\[(\w+)\](\w+(?:\{\})?)\{(.*?)\n\}" % name, src, re.S)
    body = m.group(3)
    return re.findall(r'^\s*("(?:[^"\\]|\\.)*"|\w+)\s*:\s*("(?:[^"\\]|\\.)*"|\w+|\{\})', body, re.M)


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    out = [f"// GENERATED by tools/parser-port/gen_keywords.py from pkg/parser/misc.go of {SOURCE}.",
           "// Do not edit by hand. Regenerate with: tools/parser-port/regen.sh <tidb-checkout>", ""]
    for go_name, rs_name in [("tokenMap", "KEYWORDS"), ("btFuncTokenMap", "BUILTIN_FUNCS"),
                             ("windowFuncTokenMap", "WINDOW_FUNCS"), ("aliases", "ALIASES")]:
        pairs = go_map(src, go_name)
        out.append(f"pub static {rs_name}: &[(&str, &str)] = &[")
        for k, v in pairs:
            v = v if v.startswith('"') else f'"{v}"'
            out.append(f"    ({k}, {v}),")
        out.append("];")
        print(f"{go_name}: {len(pairs)} entries", file=sys.stderr)
    hinted = [k for k, _ in go_map(src, "hintedTokens")]
    out.append("pub static HINTED_TOKENS: &[&str] = &[" + ", ".join(f'"{h}"' for h in hinted) + "];")
    open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
