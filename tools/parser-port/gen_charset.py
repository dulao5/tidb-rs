#!/usr/bin/env python3
"""Extract the charset / collation tables of TiDB charset.go into crates/parser/src/charset_gen.rs.

Usage: python3 -I tools/parser-port/gen_charset.py <charset.go> <out.rs>
(normally run through tools/parser-port/regen.sh)
Tables:
  SUPPORTED_CHARSETS  CharacterSetInfos (name, default collation): charsets TiDB accepts
  KNOWN_CHARSETS      charsets (name, default collation): known to MySQL, "Unsupported" in TiDB
  COLLATIONS          collations (id, charset, name): every collation GetCollationByName finds
"""
import os
import re
import sys

SOURCE = os.environ.get("PARSER_PORT_SOURCE", "TiDB (unknown commit)")


def block(src, start):
    i = src.index(start)
    j = src.index("\n}\n", i)
    return src[i:j]


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    consts = dict(re.findall(r'^\s*((?:Charset|Collation)\w+)\s*=\s*"([^"]*)"', src, re.M))

    def val(tok):
        tok = tok.strip()
        return tok[1:-1] if tok.startswith('"') else consts[tok]

    supported = re.findall(r"^\s*(\w+):\s*\{(\w+),\s*(\w+),", block(src, "var CharacterSetInfos"), re.M)
    supported = [(val(n), val(c)) for _, n, c in supported]
    known = re.findall(r'^\s*\w+:\s*\{Name:\s*(\w+),.*?DefaultCollation:\s*("[^"]*"|\w+)',
                       block(src, "var charsets = "), re.M)
    known = [(val(n), val(c)) for n, c in known]
    colls = re.findall(r'^\s*\{(\d+),\s*"([^"]*)",\s*"([^"]*)",', block(src, "var collations = "), re.M)
    if not supported or not known or not colls:
        raise SystemExit("charset.go layout changed: nothing extracted")
    out = [f"// GENERATED by tools/parser-port/gen_charset.py from pkg/parser/charset/charset.go of {SOURCE}.",
           "// Do not edit by hand. Regenerate with: tools/parser-port/regen.sh <tidb-checkout>", "",
           "/// CharacterSetInfos: (name, default collation) of the charsets TiDB supports.",
           "pub static SUPPORTED_CHARSETS: &[(&str, &str)] = &["]
    out += [f'    ("{n}", "{c}"),' for n, c in sorted(supported)]
    out += ["];", "/// charsets: (name, default collation) of every charset known to MySQL.",
            "pub static KNOWN_CHARSETS: &[(&str, &str)] = &["]
    out += [f'    ("{n}", "{c}"),' for n, c in sorted(known)]
    out += ["];", "/// collations: (id, charset, name).", "pub static COLLATIONS: &[(u16, &str, &str)] = &["]
    out += [f'    ({i}, "{c}", "{n}"),' for i, c, n in colls]
    out.append("];")
    open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"charsets: {len(supported)} supported, {len(known)} known; collations: {len(colls)}",
          file=sys.stderr)


if __name__ == "__main__":
    main()
