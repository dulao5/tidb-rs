#!/usr/bin/env python3
"""Generate the built-in function registry data of tidb-expression from TiDB sources.

    tools/expr-gen/gen_registry.py <tidb-checkout>

Writes
  crates/expression/src/ast_funcs.rs     the function-name constants of pkg/parser/ast/functions.go
  crates/expression/src/builtin_registry_gen.rs
                                         the entries of `funcs` in pkg/expression/builtin.go:
                                         map key, function class type, baseFunctionClass
                                         {funcName, minArgs, maxArgs} and, for the classes
                                         with getDisplayName (compareFunctionClass,
                                         isTrueOrFalseFunctionClass), opcode.Op.Format.
"""

import os
import re
import sys

tidb = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
out_dir = os.path.join(here, "..", "..", "crates", "expression", "src")


def read(p):
    with open(os.path.join(tidb, p), encoding="utf-8") as f:
        return f.read()


rev = os.popen(f"git -C {tidb} rev-parse --short=9 HEAD").read().strip()

# ---- ast function names
fsrc = read("pkg/parser/ast/functions.go")
names = []
seen = set()
for blk in re.findall(r"\nconst \((.*?)\n\)", fsrc, re.S):
    for m in re.finditer(r"^\s*(\w+)\s*=\s*\"([^\"]*)\"", blk, re.M):
        ident, val = m.group(1), m.group(2)
        if ident in seen:
            continue
        seen.add(ident)
        names.append((ident, val))

with open(os.path.join(out_dir, "ast_funcs.rs"), "w", encoding="utf-8") as f:
    f.write(f"// GENERATED by tools/expr-gen/gen_registry.py from pkg/parser/ast/functions.go of TiDB {rev}.\n")
    f.write("// Do not edit by hand.\n\n")
    f.write("//! The string constants of `pkg/parser/ast/functions.go`: the lower-case names of the\n")
    f.write("//! built-in functions (`ast.Coalesce` = `\"coalesce\"`).\n\n")
    f.write("#![allow(non_upper_case_globals)]\n\n")
    for ident, val in names:
        esc = val.replace("\\", "\\\\").replace('"', '\\"')
        f.write(f'pub const {ident}: &str = "{esc}";\n')

# ---- opcode literals
osrc = read("pkg/parser/opcode/opcode.go")
lits = {}
for m in re.finditer(r"^\t(\w+): \{\n\t\tname:\s+\"[^\"]*\",\n\t\tliteral:\s+\"([^\"]*)\"", osrc, re.M):
    lits[m.group(1)] = m.group(2)

# ---- funcs map
bsrc = read("pkg/expression/builtin.go")
body = re.search(r"var funcs = map\[string\]functionClass\{\n(.*?)\n\}\n", bsrc, re.S).group(1)
ent = re.compile(
    r"^\s*ast\.(\w+):\s*&(\w+)\{(?:baseFunctionClass:\s*)?baseFunctionClass\{ast\.(\w+),\s*(-?\d+),\s*(-?\d+)\}(.*)$"
)
display_classes = {"compareFunctionClass", "isTrueOrFalseFunctionClass"}
rows = []
for line in body.split("\n"):
    s = line.strip()
    if not s or s.startswith("//"):
        continue
    m = ent.match(line)
    if not m:
        sys.exit(f"unparsed funcs entry: {line}")
    key, cls, fname, mn, mx, rest = m.groups()
    disp = None
    if cls in display_classes:
        op = re.search(r"opcode\.(\w+)", rest).group(1)
        disp = lits[op]
    rows.append((key, cls, fname, int(mn), int(mx), disp))

with open(os.path.join(out_dir, "builtin_registry_gen.rs"), "w", encoding="utf-8") as f:
    f.write(f"// GENERATED by tools/expr-gen/gen_registry.py from pkg/expression/builtin.go of TiDB {rev}.\n")
    f.write("// Do not edit by hand.\n\n")
    f.write("use crate::ast_funcs as ast;\n")
    f.write("use crate::builtin::BaseFunctionClass;\n")
    f.write("use crate::builtin_registry::FuncClassEntry;\n\n")
    f.write(f"/// The {len(rows)} entries of Go's `funcs`, in source order.\n")
    f.write("pub(crate) static FUNCS: &[FuncClassEntry] = &[\n")
    for key, cls, fname, mn, mx, disp in rows:
        d = "None" if disp is None else f'Some("{disp}")'
        f.write(
            f"    FuncClassEntry {{ name: ast::{key}, class: \"{cls}\", base: BaseFunctionClass {{ func_name: ast::{fname}, min_args: {mn}, max_args: {mx} }}, display_name: {d} }},\n"
        )
    f.write("];\n")
print(f"{len(names)} names, {len(rows)} funcs entries")
