#!/usr/bin/env python3
"""Generate the pb code -> signature table of `getSignatureByPB` (tidb-expr-pushdown,
block D08.3 part 2).

    tools/expr-gen/gen_pb_sigs.py <tidb-checkout> <tidb-rs-tracker>

Reads pkg/expression/distsql_builtin.go (TiDB v8.5.8) and writes
crates/expr-pushdown/src/distsql_builtin_gen.rs:

  PB_SIGS   one row per pb code of the `switch sigCode` in `getSignatureByPB`:
            the code, the Go signature type of the struct literal, how the literal builds it
            (`Ctor`) and the block that owns the signature type (tracker
            data/func_blocks.tsv, the block of `<type>.Clone`), in the order of the Go cases;
  PORTED    every `SigDesc` static of tidb-expression (crates/expression/src/*.rs: the first
            argument of the `*_sig!` macros and the explicit `pub static ...: SigDesc`), the
            signatures `getSignatureByPB` can build; the others are boundary stubs.

Rerun when a function family adds signatures.
"""

import csv
import os
import re
import sys

tidb, tracker = sys.argv[1], sys.argv[2]
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, "..", "..")
out = os.path.join(root, "crates", "expr-pushdown", "src", "distsql_builtin_gen.rs")

src = open(os.path.join(tidb, "pkg/expression/distsql_builtin.go"), encoding="utf-8").read()
body = src[src.index("switch sigCode {") : src.index("\tdefault:\n\t\te = ErrFunctionNotExists")]
body = re.sub(r"//[^\n]*", "", body)

blocks = {}
with open(os.path.join(tracker, "data", "func_blocks.tsv"), newline="") as f:
    for row in csv.DictReader(f, delimiter="\t"):
        if row["pkg"] == "pkg/expression" and row["symbol"].endswith(".Clone"):
            blocks[row["symbol"][: -len(".Clone")]] = row["block"]

rows = []
for case in re.split(r"\n\tcase ", body)[1:]:
    head, rest = case.split(":\n", 1)
    codes = re.findall(r"tipb\.ScalarFuncSig_(\w+)", head)
    rest = " ".join(rest.split())
    if "addSubDateFunctionClass" in rest:
        sub = "ast.SubDate" in rest
        ctor = f"Ctor::AddSubDate {{ sub: {'true' if sub else 'false'} }}"
        go, block = "addSubDateFunctionClass", blocks.get("builtinAddSubDateAsStringSig", "D08.7")
    else:
        m = re.fullmatch(r"f = &(\w+)\{(.*)\}", rest)
        if not m:
            sys.exit(f"unrecognised case {head}: {rest}")
        go, init = m.group(1), m.group(2).strip()
        block = blocks.get(go)
        if block is None:
            sys.exit(f"no block for {go}")
        if init in ("base", "baseBuiltinFunc: base") or re.fullmatch(r"(\w+: )?\w+\{(baseBuiltinFunc: )?base\}", init) \
                or re.fullmatch(r"\w+: \w+\{baseBuiltinFunc: base\}", init):
            ctor = "Ctor::Base"
        elif init == "newBaseBuiltinCastFunc(base, false)":
            ctor = "Ctor::Cast { in_union: false }"
        elif init == "base, maxAllowedPacket":
            ctor = "Ctor::MaxAllowedPacket"
        elif m2 := re.fullmatch(r"base, (true|false)", init):
            field = {
                "builtinGreatestTimeSig": "Extremum", "builtinLeastTimeSig": "Extremum",
                "builtinGreatestCmpStringAsTimeSig": "Extremum", "builtinLeastCmpStringAsTimeSig": "Extremum",
                "builtinIntervalIntSig": "IntervalInt", "builtinIntervalRealSig": "IntervalReal",
                "builtinUnaryMinusDecimalSig": "UnaryMinusDecimal",
                "builtinIntIsTrueSig": "IsTrueOrFalse", "builtinRealIsTrueSig": "IsTrueOrFalse",
                "builtinDecimalIsTrueSig": "IsTrueOrFalse", "builtinIntIsFalseSig": "IsTrueOrFalse",
                "builtinRealIsFalseSig": "IsTrueOrFalse", "builtinDecimalIsFalseSig": "IsTrueOrFalse",
                "builtinInternalFromBinarySig": "FromBinary",
            }[go]
            ctor = f"Ctor::{field}({m2.group(1)})"
        else:
            sys.exit(f"unrecognised literal {go}{{{init}}}")
    for c in codes:
        rows.append((c, go, ctor, block))

ported = []
for fn in sorted(os.listdir(os.path.join(root, "crates", "expression", "src"))):
    if not fn.endswith(".rs"):
        continue
    text = open(os.path.join(root, "crates", "expression", "src", fn), encoding="utf-8").read()
    mod = fn[:-3]
    names = re.findall(r"^\s*\w*sig!\(\s*(builtin\w+)", text, re.M)
    names += re.findall(r"^pub static (builtin\w+): SigDesc", text, re.M)
    for n in names:
        ported.append(f"&tidb_expression::{mod}::{n}")

lines = [
    "// Code generated by tools/expr-gen/gen_pb_sigs.py from TiDB v8.5.8",
    "// pkg/expression/distsql_builtin.go and crates/expression/src. DO NOT EDIT.",
    "",
    "#![allow(non_upper_case_globals)]",
    "",
    "use tidb_expression::eval::SigDesc;",
    "",
    "use super::Ctor;",
    "use crate::tipb_sig::*;",
    "",
    "/// The cases of `getSignatureByPB`: pb code, Go signature type, struct literal, owning block.",
    "pub(crate) static PB_SIGS: &[(i32, &str, Ctor, &str)] = &[",
]
for c, go, ctor, block in rows:
    lines.append(f'    ({c}, "{go}", {ctor}, "{block}"),')
lines += ["];", "", "/// The signatures of tidb-expression.", "pub(crate) static PORTED: &[&SigDesc] = &["]
lines += [f"    {p}," for p in ported]
lines += ["];"]
with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print(f"{out}: {len(rows)} pb codes, {len(ported)} ported signatures")
