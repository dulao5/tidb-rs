#!/usr/bin/env python3
"""Generate the tipb ScalarFuncSig table of tidb-expr-pushdown from the tipb Go module TiDB
v8.5.8 uses.

    tools/expr-gen/gen_tipb_sigs.py <go-tipb-module-dir>

e.g. $(go env GOMODCACHE)/github.com/pingcap/tipb@v0.0.0-20260605083900-f9f651ef5fbc (the
version in TiDB v8.5.8's go.mod). Writes crates/expr-pushdown/src/tipb_sig_gen.rs: one Rust
constant per value of `enum ScalarFuncSig` in proto/expression.proto, named as Go's
`tipb.ScalarFuncSig_<Name>` (the Rust tipb crate renames them, e.g. `LTJson` -> `LtJson`, and is
a newer revision with more values), and `NAMES`, Go's `ScalarFuncSig_name` map sorted by value
for `ScalarFuncSig.String()`.
"""

import os
import re
import sys

tipb = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "..", "crates", "expr-pushdown", "src", "tipb_sig_gen.rs")

with open(os.path.join(tipb, "proto", "expression.proto"), encoding="utf-8") as f:
    src = f.read()
body = re.search(r"\nenum ScalarFuncSig \{(.*?)\n\}", src, re.S).group(1)
body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
body = re.sub(r"//[^\n]*", "", body)
sigs = [(m.group(1), int(m.group(2))) for m in re.finditer(r"^\s*(\w+)\s*=\s*(-?\d+)\s*;", body, re.M)]
names = {}
for n, v in sigs:
    # Go's ScalarFuncSig_name keeps the first name of a value (protoc-gen-gogo).
    names.setdefault(v, n)

version = os.path.basename(os.path.normpath(tipb))
lines = [
    "// Code generated by tools/expr-gen/gen_tipb_sigs.py from",
    f"// github.com/pingcap/tipb {version.split('@')[-1]} proto/expression.proto. DO NOT EDIT.",
    "//",
    "// Go's `tipb.ScalarFuncSig_<Name>` constants and `ScalarFuncSig_name`.",
    "",
    "#![allow(non_upper_case_globals)]",
    "",
]
for n, v in sigs:
    lines.append(f"pub const {n}: i32 = {v};")
lines.append("")
lines.append("/// Go's `ScalarFuncSig_name`, sorted by value.")
lines.append("pub(crate) static NAMES: &[(i32, &str)] = &[")
for v in sorted(names):
    lines.append(f'    ({v}, "{names[v]}"),')
lines.append("];")
with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print(f"{out}: {len(sigs)} constants, {len(names)} names")
