use std::sync::Arc;

use tidb_base::Error;
use tidb_expression::util::{expr_has_set_var_or_sleep, extract_columns_from_expressions};
use tidb_expression::{Column, Expr, ExprRef, Schema, get_used_list, new_zero};

use crate::arena::PlanId;
use crate::base::{LogicalKind, LogicalPlan, ReplaceMap, prune_columns};
use crate::logicalop::{BaseLogicalPlan, LogicalSchemaProducer, logical_plan_boilerplate};
use crate::optimizetrace::{LogicalOptimizeOp, logicaltrace};
use crate::planctx::PlanCtx;
use crate::rule_util::resolve_expr_and_replace;

/// LogicalProjection represents a select fields plan.
pub struct LogicalProjection {
    /// BaseLogicalPlan.
    pub base: BaseLogicalPlan,
    /// LogicalSchemaProducer.
    pub sp: LogicalSchemaProducer,
    /// Exprs.
    pub exprs: Vec<ExprRef>,
    /// CalculateNoDelay indicates this Projection is the root Plan and should be
    /// calculated without delay and will not return any result to client.
    pub calculate_no_delay: bool,
    /// Proj4Expand is used for expand to project same column reference, while these
    /// col may be filled with null so we couldn't just eliminate this projection itself.
    pub proj4_expand: bool,
}

impl LogicalProjection {
    /// Init initializes LogicalProjection (plus `SetSchema`).
    // go: pkg/planner/core/operator/logicalop/logical_projection.go LogicalProjection.Init L1 [M-PLAN]
    pub fn init(
        exprs: Vec<ExprRef>,
        schema: Schema,
        ctx: &PlanCtx<'_>,
        qb_offset: i32,
    ) -> LogicalProjection {
        LogicalProjection {
            base: BaseLogicalPlan::new(ctx, "Projection", qb_offset),
            sp: LogicalSchemaProducer::new(Some(schema)),
            exprs,
            calculate_no_delay: false,
            proj4_expand: false,
        }
    }
}

impl LogicalPlan for LogicalProjection {
    logical_plan_boilerplate!(Projection, producer);

    /// ReplaceExprColumns implements base.LogicalPlan interface.
    // go: pkg/planner/core/operator/logicalop/logical_projection.go (*LogicalProjection).ReplaceExprColumns L1 [M-EXPR]
    fn replace_expr_columns(&mut self, replace: &ReplaceMap) {
        for expr in self.exprs.iter_mut() {
            resolve_expr_and_replace(expr, replace);
        }
    }

    /// PruneColumns implements base.LogicalPlan.<2nd> interface.
    /// If any expression has SetVar function or Sleep function, we do not prune it.
    // go: pkg/planner/core/operator/logicalop/logical_projection.go (*LogicalProjection).PruneColumns L1 [M-PLAN, M-EXPR]
    fn prune_columns(
        &mut self,
        ctx: &mut PlanCtx<'_>,
        this: PlanId,
        parent_used_cols: Vec<Arc<Column>>,
        opt: &mut LogicalOptimizeOp,
    ) -> Result<PlanId, Error> {
        let mut used = get_used_list(&*ctx.eval_ctx(), &parent_used_cols, self.schema(&ctx.arena));
        let mut pruned_columns = Vec::new();

        let mut all_pruned = true;
        for (i, b) in used.iter_mut().enumerate() {
            if *b || expr_has_set_var_or_sleep(&self.exprs[i]) {
                // Set to true to avoid the ExprHasSetVarOrSleep be called multiple times.
                *b = true;
                all_pruned = false;
                break;
            }
        }
        if all_pruned && ctx.arena.get(self.children()[0]).kind() == LogicalKind::TableDual {
            // If the child is dual. The proj should not be eliminated.
            // When the dual is generated by `select ....;`` directly(No source SELECT), the dual is created without any output cols.
            // The dual only holds a RowCount, and the proj is used to generate the output cols.
            // But we need reset the used columns in its expression since there can be correlated columns in the expression.
            // Go: `p.Exprs[:1]` re-slices into the capacity when Exprs is empty (and
            // panics when the capacity is 0); the element is overwritten right after.
            self.exprs.truncate(1);
            if self.exprs.is_empty() {
                self.exprs.push(Expr::Constant(new_zero()).into_ref());
            }
            self.schema_mut(&mut ctx.arena).columns.truncate(1);
            self.exprs[0] = Expr::Constant(new_zero()).into_ref();
            let col = Column {
                unique_id: ctx.vars.alloc_plan_column_id(),
                ret_type: Arc::new(self.exprs[0].get_type(&*ctx.eval_ctx()).into_owned()),
                ..Column::default()
            };
            let schema = self.schema_mut(&mut ctx.arena);
            if schema.columns.is_empty() {
                schema.columns.push(Arc::new(col));
            } else {
                schema.columns[0] = Arc::new(col);
            }
            return Ok(this);
        }

        // for implicit projected cols, once the ancestor doesn't use it, the implicit expr will be automatically pruned here.
        for i in (0..used.len()).rev() {
            if !used[i] && !expr_has_set_var_or_sleep(&self.exprs[i]) {
                pruned_columns.push(self.schema(&ctx.arena).columns[i].clone());
                self.schema_mut(&mut ctx.arena).columns.remove(i);
                self.exprs.remove(i);
            }
        }
        logicaltrace::append_column_prune_trace_step(self, &pruned_columns, opt);
        let mut self_used_cols = Vec::with_capacity(self.exprs.len());
        self_used_cols = extract_columns_from_expressions(self_used_cols, &self.exprs, None);
        self.children_mut()[0] = prune_columns(ctx, self.children()[0], self_used_cols, opt)?;
        // If its columns are all pruned, we directly use its child. The child will output at least one column.
        if self.schema(&ctx.arena).is_empty() {
            return Ok(self.children()[0]);
        }
        Ok(this)
    }
}
