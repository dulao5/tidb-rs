#[derive(Clone)]
struct ArgType {
    name: &'static str,
    ft: FieldType,
    values: Vec<Datum>,
}

fn num_ft(tp: u8, flen: isize, dec: isize, unsigned: bool) -> FieldType {
    let mut flag = mysql::BinaryFlag;
    if unsigned {
        flag |= mysql::UnsignedFlag;
    }
    new_field_type_builder()
        .set_type(tp)
        .set_flag(flag)
        .set_flen(flen)
        .set_decimal(dec)
        .set_charset("binary")
        .set_collate("binary")
        .build_p()
}

fn str_ft(tp: u8, flen: isize, charset: &str, collate: &str) -> FieldType {
    let flag = if collate == "binary" {
        mysql::BinaryFlag
    } else {
        0
    };
    new_field_type_builder()
        .set_type(tp)
        .set_flag(flag)
        .set_flen(flen)
        .set_decimal(0)
        .set_charset(charset)
        .set_collate(collate)
        .build_p()
}

/// A value of `ft` from a literal: the datum converted to the column type as an INSERT in a
/// strict statement would (the conversion must succeed without warnings).
fn val(ft: &FieldType, mut d: Datum) -> Datum {
    if d.is_null() {
        return d;
    }
    let (out, res) = d.convert_to(&DefaultStmtNoWarningContext, ft);
    res.unwrap_or_else(|e| panic!("edge value {d:?} for {}: {e:?}", ft.compact_str()));
    out
}

fn ints(ft: &FieldType, xs: &[i64]) -> Vec<Datum> {
    let mut v = vec![Datum::default()];
    v.extend(xs.iter().map(|&x| val(ft, dm::new_int_datum(x))));
    v
}

fn uints(ft: &FieldType, xs: &[u64]) -> Vec<Datum> {
    let mut v = vec![Datum::default()];
    v.extend(xs.iter().map(|&x| val(ft, dm::new_uint_datum(x))));
    v
}

fn floats(ft: &FieldType, xs: &[f64]) -> Vec<Datum> {
    let mut v = vec![Datum::default()];
    v.extend(xs.iter().map(|&x| {
        let mut d = dm::new_float64_datum(x);
        if ft.get_type() == mysql::TypeFloat {
            d = dm::new_float32_datum(x as f32);
        }
        d
    }));
    v
}

fn strs(ft: &FieldType, xs: &[&str]) -> Vec<Datum> {
    let mut v = vec![Datum::default()];
    v.extend(
        xs.iter()
            .map(|&x| val(ft, dm::new_string_datum(x.as_bytes().to_vec()))),
    );
    v
}

