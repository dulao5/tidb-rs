struct Classification {
    ruling: String,
    sigs: Vec<String>,
    justification: String,
}

fn ruling_ids() -> Vec<String> {
    let text = include_str!("../../../docs/testing/rulings.toml");
    let mut ids = Vec::new();
    let mut in_ruling = false;
    for line in text.lines() {
        let l = line.trim();
        if l.starts_with('[') {
            in_ruling = l == "[[ruling]]";
            continue;
        }
        if in_ruling && let Some(rest) = l.strip_prefix("id = \"") {
            ids.push(rest.trim_end_matches('"').to_owned());
        }
    }
    ids
}

fn classifications() -> Vec<Classification> {
    let text = include_str!("../../../docs/testing/rulings_pushdown.tsv");
    text.lines()
        .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
        .skip(1)
        .map(|l| {
            let f: Vec<&str> = l.split('\t').collect();
            assert!(f.len() >= 3, "rulings_pushdown.tsv: bad row {l:?}");
            Classification {
                ruling: f[0].to_owned(),
                sigs: if f[1] == "-" {
                    vec![]
                } else {
                    f[1].split(',').map(|s| s.trim().to_owned()).collect()
                },
                justification: f[2].to_owned(),
            }
        })
        .collect()
}

#[test]
fn go_bug_fixed_rulings_stay_off_pushdown_or_match_tikv() {
    let ids = ruling_ids();
    let rows = classifications();
    let run = oracle();
    let o = &run.outcome;
    let mut failures = Vec::new();

    let classified: BTreeSet<&str> = rows.iter().map(|r| r.ruling.as_str()).collect();
    for id in &ids {
        if !classified.contains(id.as_str()) {
            failures.push(format!(
                "ruling {id} is not classified in docs/testing/rulings_pushdown.tsv: say which pushable signatures it changes (or -)"
            ));
        }
    }
    for r in &rows {
        if !ids.contains(&r.ruling) {
            failures.push(format!(
                "rulings_pushdown.tsv: {} is not a ruling of rulings.toml",
                r.ruling
            ));
        }
        let j = r.justification.as_str();
        if r.sigs.is_empty() {
            if j != "none" {
                failures.push(format!(
                    "{}: no signature listed, justification must be none",
                    r.ruling
                ));
            }
            continue;
        }
        let mismatched: BTreeSet<&str> = o.mismatches.iter().map(|m| m.root_sig.as_str()).collect();
        for sig in &r.sigs {
            let go_pushes = run.pushable.contains_key(sig);
            let rs_pushes = o.covered.contains(sig);
            let rs_builds = rs_pushes || o.not_pushed.contains(sig);
            match j {
                "tikv-oracle" => {
                    if !rs_pushes {
                        failures.push(format!(
                            "{}: {sig} is justified by tikv-oracle but the oracle does not cover it",
                            r.ruling
                        ));
                    } else if mismatched.contains(sig.as_str()) {
                        failures.push(format!(
                            "{}: {sig} is justified by tikv-oracle but the oracle finds mismatches on it",
                            r.ruling
                        ));
                    }
                }
                "not-pushable" => {
                    if rs_pushes || (!rs_builds && go_pushes) {
                        failures.push(format!(
                            "{}: {sig} is justified by not-pushable but it is pushed to TiKV",
                            r.ruling
                        ));
                    }
                }
                "unported" => {
                    if rs_builds {
                        failures.push(format!(
                            "{}: {sig} is justified by unported but tidb-rs builds it now: cover it in the oracle (tikv-oracle) or keep it off pushdown",
                            r.ruling
                        ));
                    }
                }
                j if j.starts_with("evidence:") && j.len() > "evidence:".len() + 10 => {}
                j if j.starts_with("pending:") && j.len() > "pending:".len() + 2 => {}
                _ => failures.push(format!(
                    "{}: {sig}: justification {j:?} is not tikv-oracle, not-pushable, unported, evidence:<text> or pending:<ref>",
                    r.ruling
                )),
            }
            if !go_pushes
                && j != "not-pushable"
                && j != "unported"
                && !j.starts_with("evidence:")
                && !j.starts_with("pending:")
                && !rs_pushes
            {
                failures.push(format!(
                    "{}: {sig} is not a signature Go pushes to TiKV: use not-pushable",
                    r.ruling
                ));
            }
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}
