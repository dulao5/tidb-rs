//! The coprocessor evaluation oracle (#476; the architecture review #474, item R-3).
//!
//! tidb-rs evaluates an expression locally (constant folding, root-side evaluation) or pushes
//! it down to TiKV. Under CONSTITUTION art. 1.2 / 9.3 tidb-rs fixes some Go bugs while TiKV
//! keeps its own behaviour, so a function that stays pushable could give a different answer
//! depending on where it runs. This test runs every case both ways. (The vendored TiKV is
//! TiKV master plus a fork branch, `third_party/tikv/PROVENANCE.md`, not a v8.5.x release.)
//!
//! 1. tidb-rs builds the expression with `new_function` / `build_cast_function` over columns of
//!    the argument types (the signature is the one tidb-rs's own type inference picks);
//! 2. the case counts only if `infer_pushdown` lets it go to TiKV (`can_exprs_push_down`);
//! 3. the expression is converted with `PbConverter::expr_to_pb`, the bytes a push-down sends;
//! 4. local evaluation: row by row (`Expr::eval`) and vectorized (`RpnProgram`);
//! 5. TiKV evaluation: the vendored `tidb_query_expr` builds the RPN from that `tipb::Expr` and
//!    evaluates it over the same rows, which TiKV decodes from the datum encoding tidb-rs
//!    writes (`codec::encode_value`), with the `EvalConfig` of a `DagRequest` carrying the
//!    push-down flags of a SELECT (`StatementContext::push_down_flags`) and the time zone, and
//!    no SQL mode (Go's `ConstructDAGReq` sends none); the result is encoded in the chunk format TiKV answers with and decoded by the
//!    ported chunk codec, as TiDB reads a coprocessor response;
//! 6. per row: value (as the client sees it: the result type's signedness, FLOAT rounding,
//!    TIME's fsp), error or not, and the warning codes. A differing row is blamed on the
//!    deepest function call below the root that already differs on it (usually an implicit
//!    CAST), so one cause is reported once, under its own signature.
//!
//! Every mismatch is either listed in `KNOWN_MISMATCHES` with the issue that reports it, or
//! the test fails. The signatures Go v8.5.8 pushes to TiKV are listed in
//! `tests/data/tikv_pushable_sigs.tsv` (generated by `tools/expr-gen/gen_tikv_pushable_sigs.py`);
//! in the families the oracle covers, a pushable signature it does not reach must be listed in
//! `NOT_COVERED` with the reason.
//!
//! The vendored TiKV fork carries fixes for two TiKV panics that TiKV v8.5.8 still has (#523,
//! #524); the inputs that reach them are listed, exactly, in `FORK_DIVERGENCES`.
//!
//! The second test (`go_bug_fixed_rulings_stay_off_pushdown_or_match_tikv`) is the rule of
//! #476 part 2: every ruling of `docs/testing/rulings.toml` is classified in
//! `docs/testing/rulings_pushdown.tsv`; a ruling that changes a signature Go pushes to TiKV
//! needs a recorded justification that this test checks.
//!
//! `COPR_ORACLE_REPORT=1` prints the coverage table and every mismatch.

