struct Env {
    eval: Arc<es::EvalContext>,
    build: Arc<es::ExprContext>,
    client: Arc<dyn Client>,
    tikv_cfg: Arc<EvalConfig>,
}

impl Env {
    /// A SELECT statement's contexts: `ResetContextOfStmt`'s type flags and error levels for a
    /// SELECT (truncation and division by zero are warnings), the default SQL mode, UTC.
    fn new() -> Env {
        set_new_collation_enabled_for_test(true);
        let mut sc = new_stmt_ctx();
        sc.in_select_stmt = true;
        let mut levels = sc.err_levels();
        levels[tidb_sessionctx::errctx::ErrGroupDividedByZero.0 as usize] =
            tidb_sessionctx::errctx::LevelWarn;
        sc.set_type_flags(
            sc.type_flags()
                .with_truncate_as_warning(true)
                .with_ignore_zero_in_date(true)
                .with_allow_negative_to_unsigned(true),
        );
        sc.set_err_levels(levels);
        let eval = es::new_eval_context(vec![
            es::with_location(Some(utc())),
            es::with_type_flags(sc.type_flags()),
            es::with_err_level_map(sc.err_levels()),
        ]);
        let build = es::new_expr_context(vec![es::with_eval_ctx(Arc::clone(&eval))]);

        let mut dag = tipb::DagRequest::default();
        dag.set_flags(sc.push_down_flags());
        dag.set_time_zone_name("UTC".to_owned());
        dag.set_time_zone_offset(0);
        // Go's `ConstructDAGReq` (pkg/executor/internal/builder/builder_utils.go)
        // sends no sql_mode, so TiKV evaluates with an empty one.
        dag.set_div_precision_increment(4);
        let tikv_cfg = Arc::new(EvalConfig::from_request(&dag).unwrap());
        Env {
            eval,
            build,
            client: Arc::new(NoSendClient),
            tikv_cfg,
        }
    }

    fn ctx(&self) -> &dyn EvalContext {
        &*self.eval
    }

    fn bctx(&self) -> &dyn BuildContext {
        &*self.build
    }

    fn take_warnings(&self) -> Vec<u16> {
        let mut codes: Vec<u16> = self
            .eval
            .truncate_warnings(0)
            .iter()
            .map(|w| to_sql_error(&w.err).code)
            .collect();
        codes.sort();
        codes
    }
}

