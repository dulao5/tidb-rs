fn cases(types: &[ArgType]) -> Vec<Case> {
    let idx = |name: &str| types.iter().position(|t| t.name == name).unwrap();
    let mut v = Vec::new();
    // Zero arguments.
    v.push(Case {
        label: "pi()".into(),
        func: ast::PI,
        args: vec![],
        cast_to: None,
    });
    // Unary functions over every type.
    for f in unary_funcs() {
        for (i, t) in types.iter().enumerate() {
            v.push(Case {
                label: format!("{f}({})", t.name),
                func: f,
                args: vec![Arg::Col(i)],
                cast_to: None,
            });
        }
    }
    // Binary functions over the pair grid.
    for f in binary_funcs() {
        for a in PAIR_TYPES {
            for b in PAIR_TYPES {
                v.push(Case {
                    label: format!("{f}({a}, {b})"),
                    func: f,
                    args: vec![Arg::Col(idx(a)), Arg::Col(idx(b))],
                    cast_to: None,
                });
            }
        }
    }
    // Same-type pairs of the other types (collations, YEAR, FLOAT, INT, narrow types).
    for t in types
        .iter()
        .map(|t| t.name)
        .filter(|n| !PAIR_TYPES.contains(n))
    {
        for f in binary_funcs() {
            v.push(Case {
                label: format!("{f}({t}, {t})"),
                func: f,
                args: vec![Arg::Col(idx(t)), Arg::Col(idx(t))],
                cast_to: None,
            });
        }
    }
    // Three-argument control functions (IF, CASE WHEN, COALESCE).
    for a in PAIR_TYPES {
        for f in [ast::If, ast::Case, ast::Coalesce] {
            v.push(Case {
                label: format!("{f}(bigint, {a}, {a})"),
                func: f,
                args: vec![Arg::Col(idx("bigint")), Arg::Col(idx(a)), Arg::Col(idx(a))],
                cast_to: None,
            });
        }
    }
    // CONV with constant bases.
    let int_ft = num_ft(mysql::TypeLonglong, 20, 0, false);
    for t in ["varchar utf8mb4_bin", "bigint", "bigint unsigned", "double"] {
        for (from, to) in [(10, 2), (16, 10), (10, -10), (36, 10)] {
            v.push(Case {
                label: format!("conv({t}, {from}, {to})"),
                func: ast::Conv,
                args: vec![
                    Arg::Col(idx(t)),
                    Arg::Const(dm::new_int_datum(from), int_ft.clone()),
                    Arg::Const(dm::new_int_datum(to), int_ft.clone()),
                ],
                cast_to: None,
            });
        }
    }
    // CAST from every type to every target.
    for (i, t) in types.iter().enumerate() {
        for (name, ft) in cast_targets() {
            v.push(Case {
                label: format!("cast({} as {name})", t.name),
                func: ast::Cast,
                args: vec![Arg::Col(i)],
                cast_to: Some(ft),
            });
        }
    }
    v
}

