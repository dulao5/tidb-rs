//! Port of Go TiDB v8.5.8 `pkg/planner` (blocks D09.x, D10.x, D13.1–D13.3; N0 rank 13).
//!
//! This crate starts with the plan representation of N1
//! (`specs/exceptions/N1-plan-representation/spec.md`), taken over from the D09.7 design
//! pilot (`crates/spike/planner-pilot`, `specs/D09.7-column-pruning/pilot-report.md`):
//!
//! - logical plans live in a per-statement [`PlanArena`] and refer to each other by
//!   [`PlanId`] (N1 §3.1, mapping rule `M-PLAN`);
//! - a Go interface method on a node in the arena is a free dispatch function that detaches
//!   the node and calls the trait method with `&mut self` next to `&mut PlanCtx`
//!   ([`with_detached`], [`logical_dispatch!`]; N1 §4);
//! - Go's struct embedding and `self` back-pointer become accessors generated by
//!   [`logical_plan_boilerplate!`] and trait default methods (`M-SELF`, N1 §3.7);
//! - physical plans are `Arc` trees from the start: [`make_mut_plan`] changes a node in place
//!   while the statement owns it and copies it once shared; [`map_children`] is Go's
//!   `p.Children()[i] = f(child)` (N1 §3.4–§3.5).
//!
//! The operators, the plan builder and the optimizer are ported by the VS1 work items
//! (`specs/VS1-vertical-slice/tasks.md`); each block plan follows `specs/templates/plan.md`.
