/// PhysPlanPartInfo indicates partition helper info in physical plan.
// go: PhysPlanPartInfo.Clone L2 (N1 immutable Arc<Expr> / Arc<Column> sharing)
#[derive(Clone, Debug, Default)]
pub struct PhysPlanPartInfo {
    /// PruningConds.
    pub pruning_conds: Vec<ExprRef>,
    /// PartitionNames.
    pub partition_names: Vec<CIStr>,
    /// Columns.
    pub columns: Vec<Arc<Column>>,
    /// ColumnNames.
    pub column_names: NameSlice,
}

/// `unsafe.Sizeof(PhysPlanPartInfo{})` on 64-bit Go (`emptyPartitionInfoSize`).
const EMPTY_PARTITION_INFO_SIZE: i64 = 96;

impl PhysPlanPartInfo {
    /// MemoryUsage return the memory usage of PhysPlanPartInfo
    ///
    /// Go's nil receiver is `pi: None`.
    // go: PhysPlanPartInfo.MemoryUsage L1
    pub fn memory_usage(pi: Option<&PhysPlanPartInfo>) -> i64 {
        let Some(pi) = pi else {
            return 0;
        };
        let mut sum = EMPTY_PARTITION_INFO_SIZE;
        for cond in &pi.pruning_conds {
            sum += cond.memory_usage();
        }
        for cis in &pi.partition_names {
            sum += cis.memory_usage();
        }
        for col in &pi.columns {
            sum += col.memory_usage();
        }
        for col_name in &pi.column_names {
            sum += col_name.memory_usage();
        }
        sum
    }
}

impl PhysicalTableReader {
    /// GetTablePlan exports the tablePlan.
    // go: PhysicalTableReader.GetTablePlan L1
    pub fn get_table_plan(&self) -> Option<&PhysicalPlanRef> {
        self.table_plan.as_ref()
    }

    /// GetTableScans exports the tableScan that contained in tablePlans.
    // go: PhysicalTableReader.GetTableScans L1
    pub fn get_table_scans(&self) -> Vec<&PhysicalTableScan> {
        let mut table_scans = Vec::with_capacity(1);
        for table_plan in &self.table_plans {
            if let Some(table_scan) = table_plan.as_any().downcast_ref::<PhysicalTableScan>() {
                table_scans.push(table_scan);
            }
        }
        table_scans
    }

    /// GetTableScan exports the tableScan that contained in tablePlans and return error when the count of table scan != 1.
    // go: PhysicalTableReader.GetTableScan L1
    pub fn get_table_scan(&self) -> Result<&PhysicalTableScan, Error> {
        let table_scans = self.get_table_scans();
        if table_scans.len() != 1 {
            return Err(errors::new("the count of table scan != 1"));
        }
        Ok(table_scans[0])
    }

    /// GetAvgRowSize return the average row size of this plan.
    // go: PhysicalTableReader.GetAvgRowSize L1 [M-CTX]
    pub fn get_avg_row_size(&self, ctx: &PlanCtx<'_>) -> f64 {
        let table_plan = self
            .table_plan
            .as_deref()
            .expect("runtime error: invalid memory address or nil pointer dereference");
        let default_coll = HistColl::default();
        let tbl_stats = get_tbl_stats(table_plan)
            .map(Arc::as_ref)
            .unwrap_or(&default_coll);
        crate::cardinality::row_size::get_avg_row_size(
            ctx,
            tbl_stats,
            &table_plan.schema().columns,
            false,
            false,
        )
    }
}

/// setMppOrBatchCopForTableScan set IsMPPOrBatchCop for all TableScan.
// go: setMppOrBatchCopForTableScan L1 [M-PLAN, M-IFACE]
pub fn set_mpp_or_batch_cop_for_table_scan(cur_plan: &mut PhysicalPlanRef) {
    if cur_plan.kind() == PhysicalKind::TableScan {
        make_mut_plan(cur_plan)
            .as_any_mut()
            .downcast_mut::<PhysicalTableScan>()
            .expect("PhysicalTableScan")
            .is_mpp_or_batch_cop = true;
    }
    crate::map_children(cur_plan, |mut child| {
        set_mpp_or_batch_cop_for_table_scan(&mut child);
        child
    });
}

