//! go-file: pkg/planner/core/physical_plans.go
//!
//! The physical operators of the first vertical slice (`PhysicalTableReader`,
//! `PhysicalTableScan`, `PhysicalSelection`, `PhysicalProjection`, `PhysicalLimit`,
//! `PhysicalTopN`, `PhysicalSort`, `NominalSort`, `PhysicalTableDual`) and the helpers of the
//! file they use. The other operators (index readers, joins, aggregation, window, MPP, CTE,
//! ...) are outside the slice and not ported yet.
//!
//! - Each operator embeds a [`BasePhysicalPlan`] (`base`) or, when Go embeds
//!   `physicalSchemaProducer`, a [`PhysicalSchemaProducer`] (`sp`); the `PhysicalPlan`
//!   methods are generated by [`crate::physical_plan_boilerplate!`] (`M-SELF`).
//! - Go's unexported fields that the access path code of `FindBestTask` (D10.2) writes
//!   (`fromDataSource`, `tblCols`, `tblColHists`, ...) are public: the crate is one Go
//!   package.
//! - Go's `Clone(newCtx)` is [`PhysicalPlan::clone_plan`]: a deep copy, as Go (the context
//!   argument is dropped, `M-CTX`); the structural copy used for copy-on-write is
//!   `clone_node` (N1 §3.5).
//! - `ExplainInfo` / `ExplainNormalizedInfo` (`explain.go`) and the access object
//!   (`access_object.go`) are block D10.9 (the `ResolveIndices` / `ToPB` / access object task
//!   of the slice): boundary stubs that panic with the `blocked` error like
//!   `PointGetPlan.ExplainInfo`. `PhysicalTableScan.TP` / `ExplainID` (explain.go) are not
//!   overridden yet, so a scan's TP is `TableScan` until then (spec §5).
//! - Fields Go uses only outside the slice are not carried: `TableScanAndPartitionInfos`
//!   (MPP), `SampleInfo` (TABLESAMPLE), `usedStatsInfo` (EXPLAIN of the stats status),
//!   `runtimeFilterList` / `maxWaitTimeMs` (TiFlash runtime filter), `AnnIndexExtra`
//!   (vector index).

