/// ExpandVirtualColumn expands the virtual column's dependent columns to ts's schema and column.
// go: ExpandVirtualColumn L1
pub fn expand_virtual_column(
    columns: &[Arc<ColumnInfo>],
    schema: &mut Schema,
    cols_info: &[Arc<ColumnInfo>],
) -> Vec<Arc<ColumnInfo>> {
    let mut copy_column = Vec::with_capacity(columns.len());
    copy_column.extend(columns.iter().map(Arc::clone));

    let old_num_columns = schema.columns.len();
    let mut num_extra_columns = 0;
    let mut ordinary_column_exists = false;
    for i in (0..old_num_columns).rev() {
        let cid = schema.columns[i].id;
        // Move extra columns to the end.
        // ExtraRowChecksumID is ignored here since it's treated as an ordinary column.
        // (pkg/util/rowcodec/decoder.go L206-L222 at upstream commit `3c407312a9`)
        if cid != ExtraHandleID as i64 && cid != ExtraPhysTblID as i64 {
            ordinary_column_exists = true;
            break;
        }
        num_extra_columns += 1;
    }
    if ordinary_column_exists && num_extra_columns > 0 {
        let extra_columns: Vec<Arc<Column>> = schema.columns[old_num_columns - num_extra_columns..]
            .iter()
            .map(Arc::clone)
            .collect();
        schema.columns.truncate(old_num_columns - num_extra_columns);

        let n = copy_column.len();
        let extra_column_models: Vec<Arc<ColumnInfo>> = copy_column[n - num_extra_columns..]
            .iter()
            .map(Arc::clone)
            .collect();
        copy_column.truncate(n - num_extra_columns);

        copy_column = expand_virtual_column_impl(schema, copy_column, cols_info);
        schema.columns.extend(extra_columns);
        copy_column.extend(extra_column_models);
        return copy_column;
    }
    expand_virtual_column_impl(schema, copy_column, cols_info)
}

/// `expandVirtualColumn`.
///
/// Go appends `FindColumnInfoByID(colsInfo, baseCol.ID)`, nil when the table has no such
/// column; a virtual column depends only on columns of its table, so the column is always
/// found, and a missing one panics here (`Vec<Arc<ColumnInfo>>` has no nil).
// go: expandVirtualColumn L2 (a nil ColumnInfo cannot be appended; it never is, see the doc)
fn expand_virtual_column_impl(
    schema: &mut Schema,
    mut copy_column: Vec<Arc<ColumnInfo>>,
    cols_info: &[Arc<ColumnInfo>],
) -> Vec<Arc<ColumnInfo>> {
    // Go ranges over the slice header taken before the loop appends.
    let n = schema.columns.len();
    for i in 0..n {
        let col = Arc::clone(&schema.columns[i]);
        let Some(virtual_expr) = &col.virtual_expr else {
            continue;
        };

        let base_cols = extract_dependent_columns(virtual_expr);
        for base_col in base_cols {
            if !schema.contains(&base_col) {
                let info = find_column_info_by_id(cols_info, base_col.id)
                    .map(Arc::clone)
                    .expect("the ColumnInfo of a virtual column's base column"); // nozero
                schema.columns.push(base_col);
                copy_column.push(info);
            }
        }
    }
    copy_column
}

