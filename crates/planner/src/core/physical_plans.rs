/// CollectPlanStatsVersion uses to collect the statistics version of the plan.
///
/// Go returns the map it was given; `stats_infos` is changed in place. The index readers
/// and the index scan are not ported (outside the first slice), so their arms are absent.
// go: CollectPlanStatsVersion L1 [M-IFACE]
pub fn collect_plan_stats_version(plan: &dyn PhysicalPlan, stats_infos: &mut HashMap<String, u64>) {
    for child in plan.children() {
        collect_plan_stats_version(child.as_ref(), stats_infos);
    }
    match plan.kind() {
        PhysicalKind::TableReader => {
            let cop_plan = plan
                .as_any()
                .downcast_ref::<PhysicalTableReader>()
                .expect("PhysicalTableReader");
            collect_plan_stats_version(
                cop_plan
                    .table_plan
                    .as_deref()
                    .expect("runtime error: invalid memory address or nil pointer dereference"),
                stats_infos,
            );
        }
        // *PhysicalIndexReader, *PhysicalIndexLookUpReader, *PhysicalIndexScan: not ported.
        PhysicalKind::TableScan => {
            let cop_plan = plan
                .as_any()
                .downcast_ref::<PhysicalTableScan>()
                .expect("PhysicalTableScan");
            stats_infos.insert(
                cop_plan.table.name.o.clone(),
                cop_plan
                    .stats_info()
                    .expect("runtime error: invalid memory address or nil pointer dereference")
                    .stats_version,
            );
        }
        _ => {}
    }
}

/// SafeClone clones this op.PhysicalPlan and handles its panic.
///
/// Go formats the recovered value with `%v`; the panic payload's message is used.
// go: SafeClone L1 [M-CTX]
pub fn safe_clone(v: &dyn PhysicalPlan) -> Result<PhysicalPlanRef, Error> {
    match catch_unwind(AssertUnwindSafe(|| v.clone_plan())) {
        Ok(r) => r,
        Err(payload) => {
            let msg = if let Some(s) = payload.downcast_ref::<&str>() {
                (*s).to_owned()
            } else if let Some(s) = payload.downcast_ref::<String>() {
                s.clone()
            } else {
                String::new()
            };
            let err = errors::errorf("%v", &[tidb_base::gofmt::Arg::from(msg)]);
            Err(err)
        }
    }
}

/// `appendChildCandidate`.
///
/// Panics like Go (nil pointer dereference) when the tracer has no candidate for `origin`.
// go: appendChildCandidate L1
pub fn append_child_candidate(
    origin: &dyn PhysicalPlan,
    pp: &dyn PhysicalPlan,
    op: &PhysicalOptimizeOp,
) {
    let mut trace = PlanTrace::default();
    trace.id = i64::from(pp.id());
    trace.tp = pp.tp().to_string();
    trace.explain_info = pp.explain_info();
    // TODO: trace the cost
    let candidate = CandidatePlanTrace {
        plan_trace: Some(trace),
        ..Default::default()
    };
    op.append_candidate(candidate);
    pp.append_child_candidate(op);
    let tracer = op
        .get_tracer()
        .expect("runtime error: invalid memory address or nil pointer dereference");
    let mut tracer = tracer.lock();
    tracer
        .candidates
        .as_mut()
        .and_then(|c| c.get_mut(&i64::from(origin.id())))
        .and_then(|c| c.plan_trace.as_mut())
        .expect("runtime error: invalid memory address or nil pointer dereference")
        .append_children_id(&[i64::from(pp.id())]);
}

