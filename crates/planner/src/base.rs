//! The plan interfaces of `pkg/planner/core/base/plan_base.go` in N1's representation.
//!
//! - `base.LogicalPlan` is the [`LogicalPlan`] trait. Nodes live in the [`PlanArena`] and
//!   refer to each other by [`PlanId`] (`M-PLAN`). Each Go interface method becomes a trait
//!   method `fn xxx(&mut self, ctx: &mut PlanCtx<'_>, this: PlanId, ...)` plus a dispatch
//!   function of the same name ([`crate::logical_dispatch!`]); `this` is the node's own id
//!   (Go's `return p` is `Ok(this)`).
//! - Go's `BaseLogicalPlan.self` back-pointer and struct embedding become trait default
//!   methods plus the accessors `base()` / `schema_producer()` (`M-SELF`, N1 §3.7), generated
//!   by [`crate::logical_plan_boilerplate!`].
//! - `base.PhysicalPlan` is the [`PhysicalPlan`] trait over `Arc` trees (N1 §3.4).
//!
//! Only the structural part is here; the Go methods are added with the operators and rules
//! that need them (VS1-19, VS1-23, VS1-27). The accessors below are glue until then: the Go
//! accessor functions (`Plan.ID`, `BaseLogicalPlan.Children`, ...) get their `// go:`
//! annotation when their block is ported.

use std::any::Any;

use tidb_expression::Schema;

use crate::arena::{PlanArena, PlanId};
use crate::logicalop::{BaseLogicalPlan, LogicalSchemaProducer};
use crate::physicalop::PhysicalPlanRef;

/// Logical operator kinds, for Go's `switch x := p.(type)` (`M-IFACE`, N1 §6.2). Variants
/// are added with the operators.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum LogicalKind {
    /// `*logicalop.DataSource`.
    DataSource,
    /// `*logicalop.LogicalSelection`.
    Selection,
    /// `*logicalop.LogicalProjection`.
    Projection,
    /// `*logicalop.LogicalLimit`.
    Limit,
    /// `*logicalop.LogicalSort`.
    Sort,
    /// `*logicalop.LogicalTopN`.
    TopN,
    /// `*logicalop.LogicalTableDual`.
    TableDual,
}

/// Physical operator kinds (`M-IFACE`). Variants are added with the operators.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum PhysicalKind {
    /// `*PointGetPlan`.
    PointGet,
    /// `*PhysicalTableReader`.
    TableReader,
    /// `*PhysicalTableScan`.
    TableScan,
    /// `*PhysicalSelection`.
    Selection,
    /// `*PhysicalProjection`.
    Projection,
    /// `*PhysicalLimit`.
    Limit,
    /// `*PhysicalSort`.
    Sort,
    /// `*PhysicalTopN`.
    TopN,
    /// `*PhysicalTableDual`.
    TableDual,
}

/// LogicalPlan is a tree of logical operators (`base.LogicalPlan`).
pub trait LogicalPlan: Any + Send {
    // ---- per-type boilerplate (M-IFACE / M-SELF), generated by logical_plan_boilerplate! ----

    /// The operator kind (`M-IFACE`).
    // glue: N1
    fn kind(&self) -> LogicalKind;
    /// For type assertions.
    // glue: N1
    fn as_any(&self) -> &dyn Any;
    /// For type assertions.
    // glue: N1
    fn as_any_mut(&mut self) -> &mut dyn Any;
    /// The embedded `BaseLogicalPlan`.
    // glue: N1 (Go struct embedding)
    fn base(&self) -> &BaseLogicalPlan;
    /// The embedded `BaseLogicalPlan`.
    // glue: N1 (Go struct embedding)
    fn base_mut(&mut self) -> &mut BaseLogicalPlan;
    /// The embedded `LogicalSchemaProducer`, for operators that embed one.
    // glue: N1 (Go struct embedding)
    fn schema_producer(&self) -> Option<&LogicalSchemaProducer> {
        None
    }
    /// The embedded `LogicalSchemaProducer`, for operators that embed one.
    // glue: N1 (Go struct embedding)
    fn schema_producer_mut(&mut self) -> Option<&mut LogicalSchemaProducer> {
        None
    }

    // ---- accessors of base.Plan / BaseLogicalPlan ----

    /// Go's plan id (`Plan.ID()`), not the arena index (N1 §3.6).
    // glue: accessor (Go baseimpl.Plan.ID, ported with D10.1 / VS1-19)
    fn id(&self) -> i32 {
        self.base().id
    }

    /// `Plan.TP()`.
    // glue: accessor (Go baseimpl.Plan.TP, ported with D10.1 / VS1-19)
    fn tp(&self) -> &'static str {
        self.base().tp
    }

    /// `BaseLogicalPlan.Children()`.
    // glue: accessor (Go BaseLogicalPlan.Children, ported with D09.14 / VS1-23)
    fn children(&self) -> &[PlanId] {
        &self.base().children
    }

    /// `p.Children()[i] = ...` (Go writes through the returned slice).
    // glue: accessor (Go BaseLogicalPlan.Children, ported with D09.14 / VS1-23)
    fn children_mut(&mut self) -> &mut [PlanId] {
        &mut self.base_mut().children
    }

    /// `BaseLogicalPlan.SetChildren`.
    // glue: accessor (Go BaseLogicalPlan.SetChildren, ported with D09.14 / VS1-23)
    fn set_children(&mut self, children: Vec<PlanId>) {
        self.base_mut().children = children;
    }

    /// `Schema()`: `BaseLogicalPlan` returns its child's schema, `LogicalSchemaProducer` its
    /// own (lazily cloned from the only child).
    // glue: accessor (Go BaseLogicalPlan.Schema / LogicalSchemaProducer.Schema, D09.14 / VS1-23)
    fn schema<'a>(&'a self, arena: &'a PlanArena) -> &'a Schema {
        match self.schema_producer() {
            Some(sp) => sp.schema(self.children(), arena),
            None => arena.get(self.children()[0]).schema(arena),
        }
    }

    /// `p.Schema()` for writing (Go writes through the returned `*Schema`): the own schema,
    /// or the child's for operators without one (N1 §3.3, `PlanArena::schema_mut`).
    // glue: accessor (Go BaseLogicalPlan.Schema / LogicalSchemaProducer.Schema, D09.14 / VS1-23)
    fn schema_mut<'a>(&'a mut self, arena: &'a mut PlanArena) -> &'a mut Schema {
        if self.schema_producer().is_some() {
            self.schema_producer()
                .expect("producer")
                .schema(self.children(), arena);
            return self
                .schema_producer_mut()
                .expect("producer")
                .schema_cell_mut();
        }
        let child = self.children()[0];
        arena.schema_mut(child)
    }

    /// A stand-in interface method for the pinned-idiom tests (`idiom_tests.rs`): the shape of
    /// `PredicatePushDown` (process the child, replace it with the returned root, write own
    /// fields, return `this` or a new root). Test builds only.
    #[cfg(test)]
    fn push_down(
        &mut self,
        ctx: &mut crate::PlanCtx<'_>,
        this: PlanId,
        predicates: Vec<String>,
    ) -> Result<PlanId, tidb_base::Error> {
        let _ = (ctx, predicates);
        Ok(this)
    }
}

/// PhysicalPlan is a tree of the physical operators (`base.PhysicalPlan`), shared as an
/// `Arc` tree from the start (N1 §3.4): `Send + Sync`, so a plan can go into the instance
/// plan cache and to executor workers as is.
pub trait PhysicalPlan: Any + Send + Sync {
    /// The operator kind (`M-IFACE`).
    // glue: N1
    fn kind(&self) -> PhysicalKind;
    /// Go's plan id.
    // glue: accessor (Go baseimpl.Plan.ID, ported with D10.1 / VS1-19)
    fn id(&self) -> i32;
    /// For type assertions.
    // glue: N1
    fn as_any(&self) -> &dyn Any;
    /// For type assertions.
    // glue: N1
    fn as_any_mut(&mut self) -> &mut dyn Any;
    /// `Schema()`.
    // glue: accessor (ported with D10.1 / VS1-19)
    fn schema(&self) -> &Schema;
    /// `SetSchema()`.
    // glue: accessor (ported with D10.1 / VS1-19)
    fn set_schema(&mut self, schema: Schema);
    /// `Children()`.
    // glue: accessor (ported with D10.1 / VS1-19)
    fn children(&self) -> &[PhysicalPlanRef];
    /// `p.Children()[i] = ...`; use [`crate::map_children`] to rewrite children.
    // glue: accessor (ported with D10.1 / VS1-19)
    fn children_mut(&mut self) -> &mut Vec<PhysicalPlanRef>;
    /// A shallow copy of this node: fields copied, children and expressions shared. Replaces
    /// Go's generated deep `CloneForPlanCache` for path copying (N1 §3.5).
    // glue: N1 §3.5
    fn clone_node(&self) -> PhysicalPlanRef;
}
