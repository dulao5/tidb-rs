pub type ReplaceMap = HashMap<Vec<u8>, Arc<Column>>;

/// LogicalPlan is a tree of logical operators (`base.LogicalPlan`).
///
/// The default methods are Go's promoted methods of `BaseLogicalPlan` /
/// `LogicalSchemaProducer`: each one dispatches to the ported function in
/// `logicalop/base_logical_plan.rs` or `logicalop/logical_schema_producer.rs`, and an
/// operator overrides the ones Go overrides. A method that changes the tree takes the node's
/// own id `this` (Go's `p.self`) and returns the new root; call it on a node in the arena
/// through the dispatch function of the same name below (N1 §4).
pub trait LogicalPlan: Any + Send {
    // ---- per-type boilerplate (M-IFACE / M-SELF), generated by logical_plan_boilerplate! ----

    /// The operator kind (`M-IFACE`).
    // glue: N1
    fn kind(&self) -> LogicalKind;
    /// For type assertions.
    // glue: N1
    fn as_any(&self) -> &dyn Any;
    /// For type assertions.
    // glue: N1
    fn as_any_mut(&mut self) -> &mut dyn Any;
    /// The embedded `BaseLogicalPlan`.
    // glue: N1 (Go struct embedding)
    fn base(&self) -> &BaseLogicalPlan;
    /// The embedded `BaseLogicalPlan`.
    // glue: N1 (Go struct embedding)
    fn base_mut(&mut self) -> &mut BaseLogicalPlan;
    /// The embedded `LogicalSchemaProducer`, for operators that embed one.
    // glue: N1 (Go struct embedding)
    fn schema_producer(&self) -> Option<&LogicalSchemaProducer> {
        None
    }
    /// The embedded `LogicalSchemaProducer`, for operators that embed one.
    // glue: N1 (Go struct embedding)
    fn schema_producer_mut(&mut self) -> Option<&mut LogicalSchemaProducer> {
        None
    }

    // ---- base.Plan ----

    /// Go's plan id (`Plan.ID()`), not the arena index (N1 §3.6).
    // glue: dispatch (Go baseimpl.Plan.ID)
    fn id(&self) -> i32 {
        self.base().plan.id()
    }

    /// `Plan.TP()`.
    // glue: dispatch (Go baseimpl.Plan.TP)
    fn tp(&self) -> &'static str {
        self.base().plan.tp()
    }

    /// `Plan.QueryBlockOffset()`.
    // glue: dispatch (Go baseimpl.Plan.QueryBlockOffset)
    fn query_block_offset(&self) -> isize {
        self.base().plan.query_block_offset()
    }

    /// `ExplainInfo()`. An `Err` is a boundary stub: the expression's EXPLAIN text is
    /// block D10.9.
    // glue: dispatch (Go BaseLogicalPlan.ExplainInfo)
    fn explain_info(&self, ctx: &PlanCtx<'_>) -> Result<String, Error> {
        let _ = ctx;
        Ok(logicalop::base_logical_plan::explain_info())
    }

    /// `Children()`.
    // glue: dispatch (Go BaseLogicalPlan.Children)
    fn children(&self) -> &[PlanId] {
        self.base().children()
    }

    /// `p.Children()[i] = ...` (Go writes through the returned slice).
    // glue: accessor (Go writes through the slice BaseLogicalPlan.Children returns)
    fn children_mut(&mut self) -> &mut [PlanId] {
        &mut self.base_mut().children
    }

    /// `SetChildren`.
    // glue: dispatch (Go BaseLogicalPlan.SetChildren)
    fn set_children(&mut self, children: Vec<PlanId>) {
        self.base_mut().set_children(children);
    }

    /// `SetChild`.
    // glue: dispatch (Go BaseLogicalPlan.SetChild)
    fn set_child(&mut self, i: usize, child: PlanId) {
        self.base_mut().set_child(i, child);
    }

    /// `Schema()`: `BaseLogicalPlan` returns its child's schema, `LogicalSchemaProducer` its
    /// own (lazily cloned from the only child).
    // glue: dispatch (Go BaseLogicalPlan.Schema / LogicalSchemaProducer.Schema)
    fn schema<'a>(&'a self, arena: &'a PlanArena) -> &'a Schema {
        match self.schema_producer() {
            Some(sp) => sp.schema(self.children(), arena),
            None => logicalop::base_logical_plan::schema(self.base(), arena),
        }
    }

    /// `p.Schema()` for writing (Go writes through the returned `*Schema`): the own schema,
    /// or the child's for operators without one (N1 §3.3, `PlanArena::schema_mut`).
    // glue: accessor (Go writes through the *Schema Schema() returns)
    fn schema_mut<'a>(&'a mut self, arena: &'a mut PlanArena) -> &'a mut Schema {
        if self.schema_producer().is_some() {
            self.schema_producer()
                .expect("producer")
                .schema(self.children(), arena);
            return self
                .schema_producer_mut()
                .expect("producer")
                .schema_cell_mut();
        }
        let child = self.children()[0];
        arena.schema_mut(child)
    }

    /// `OutputNames()`.
    // glue: dispatch (Go BaseLogicalPlan.OutputNames / LogicalSchemaProducer.OutputNames)
    fn output_names<'a>(&'a self, arena: &'a PlanArena) -> &'a NameSlice {
        match self.schema_producer() {
            Some(sp) => sp.output_names(self.children(), arena),
            None => logicalop::base_logical_plan::output_names(self.base(), arena),
        }
    }

    /// `ReplaceExprColumns` (Go's `baseimpl.Plan` does nothing).
    // glue: dispatch (Go baseimpl.Plan.ReplaceExprColumns)
    fn replace_expr_columns(&mut self, replace: &ReplaceMap) {
        let _ = replace;
    }

    // ---- base.LogicalPlan ----

    /// `HashCode`. An `Err` is a boundary stub (see the operators).
    // glue: dispatch (Go BaseLogicalPlan.HashCode)
    fn hash_code(&self) -> Result<Vec<u8>, Error> {
        Ok(self.base().hash_code())
    }

    /// `PredicatePushDown`: returns the predicates that stay above and the new root. An
    /// `Err` is a boundary stub (Go returns no error).
    // glue: dispatch (Go BaseLogicalPlan.PredicatePushDown)
    fn predicate_push_down(
        &mut self,
        ctx: &mut PlanCtx<'_>,
        this: PlanId,
        predicates: Vec<ExprRef>,
        opt: &LogicalOptimizeOp,
    ) -> Result<(Vec<ExprRef>, PlanId), Error> {
        logicalop::base_logical_plan::predicate_push_down(self, ctx, this, predicates, opt)
    }

    /// `PruneColumns`: returns the new root.
    // glue: dispatch (Go BaseLogicalPlan.PruneColumns)
    fn prune_columns(
        &mut self,
        ctx: &mut PlanCtx<'_>,
        this: PlanId,
        parent_used_cols: Vec<Arc<Column>>,
        opt: &LogicalOptimizeOp,
    ) -> Result<PlanId, Error> {
        logicalop::base_logical_plan::prune_columns(self, ctx, this, parent_used_cols, opt)
    }

    /// `PushDownTopN`: `top_n` is a `LogicalTopN` in the arena (Go's `nil` is `None`);
    /// returns the new root.
    // glue: dispatch (Go BaseLogicalPlan.PushDownTopN)
    fn push_down_top_n(
        &mut self,
        ctx: &mut PlanCtx<'_>,
        this: PlanId,
        top_n: Option<PlanId>,
        opt: &LogicalOptimizeOp,
    ) -> PlanId {
        logicalop::base_logical_plan::push_down_top_n(self, ctx, this, top_n, opt)
    }

    /// `DeriveTopN`.
    // glue: dispatch (Go BaseLogicalPlan.DeriveTopN)
    fn derive_top_n(
        &mut self,
        ctx: &mut PlanCtx<'_>,
        this: PlanId,
        opt: &LogicalOptimizeOp,
    ) -> Result<PlanId, Error> {
        logicalop::base_logical_plan::derive_top_n(self, ctx, this, opt)
    }

    /// `PredicateSimplification`.
    // glue: dispatch (Go BaseLogicalPlan.PredicateSimplification)
    fn predicate_simplification(
        &mut self,
        ctx: &mut PlanCtx<'_>,
        this: PlanId,
        opt: &LogicalOptimizeOp,
    ) -> Result<PlanId, Error> {
        logicalop::base_logical_plan::predicate_simplification(self, ctx, this, opt)
    }

    /// `ConstantPropagation` (only `LogicalJoin` does something; Go's `nil` is `None`).
    // glue: dispatch (Go BaseLogicalPlan.ConstantPropagation)
    fn constant_propagation(
        &mut self,
        ctx: &mut PlanCtx<'_>,
        parent: PlanId,
        current_child_idx: usize,
        opt: &LogicalOptimizeOp,
    ) -> Option<PlanId> {
        let _ = (ctx, parent, current_child_idx, opt);
        logicalop::base_logical_plan::constant_propagation()
    }

    /// `PullUpConstantPredicates`.
    // glue: dispatch (Go BaseLogicalPlan.PullUpConstantPredicates)
    fn pull_up_constant_predicates(&self, ctx: &PlanCtx<'_>) -> Vec<ExprRef> {
        let _ = ctx;
        logicalop::base_logical_plan::pull_up_constant_predicates()
    }

    /// `ExtractCorrelatedCols`.
    // glue: dispatch (Go BaseLogicalPlan.ExtractCorrelatedCols)
    fn extract_correlated_cols(&self) -> Vec<Arc<CorrelatedColumn>> {
        logicalop::base_logical_plan::extract_correlated_cols()
    }

    /// `MaxOneRow`.
    // glue: dispatch (Go BaseLogicalPlan.MaxOneRow)
    fn max_one_row(&self) -> bool {
        self.base().max_one_row()
    }

    /// `CanPushToCop`.
    // glue: dispatch (Go BaseLogicalPlan.CanPushToCop)
    fn can_push_to_cop(&self, ctx: &PlanCtx<'_>, store_tp: StoreType) -> bool {
        logicalop::logical_plans_misc::can_push_to_cop_impl(self, ctx, store_tp, false)
    }

    /// `ConvertOuterToInnerJoin`.
    // glue: dispatch (Go BaseLogicalPlan.ConvertOuterToInnerJoin)
    fn convert_outer_to_inner_join(
        &mut self,
        ctx: &mut PlanCtx<'_>,
        this: PlanId,
        predicates: Vec<ExprRef>,
    ) -> PlanId {
        logicalop::base_logical_plan::convert_outer_to_inner_join(self, ctx, this, predicates)
    }

    /// A stand-in interface method for the pinned-idiom tests (`idiom_tests.rs`): the shape of
    /// `PredicatePushDown` (process the child, replace it with the returned root, write own
    /// fields, return `this` or a new root). Test builds only.
    #[cfg(test)]
    fn push_down(
        &mut self,
        ctx: &mut crate::PlanCtx<'_>,
        this: PlanId,
        predicates: Vec<String>,
    ) -> Result<PlanId, tidb_base::Error> {
        let _ = (ctx, predicates);
        Ok(this)
    }
}

