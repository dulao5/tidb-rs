/// Logical operator kinds, for Go's `switch x := p.(type)` (`M-IFACE`, N1 §6.2). Variants
/// are added with the operators.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum LogicalKind {
    /// `*logicalop.DataSource`.
    DataSource,
    /// `*logicalop.LogicalSelection`.
    Selection,
    /// `*logicalop.LogicalProjection`.
    Projection,
    /// `*logicalop.LogicalLimit`.
    Limit,
    /// `*logicalop.LogicalSort`.
    Sort,
    /// `*logicalop.LogicalTopN`.
    TopN,
    /// `*logicalop.LogicalTableDual`.
    TableDual,
}

/// Physical operator kinds (`M-IFACE`). Variants are added with the operators.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum PhysicalKind {
    /// `*PointGetPlan`.
    PointGet,
    /// `*PhysicalTableReader`.
    TableReader,
    /// `*PhysicalTableScan`.
    TableScan,
    /// `*PhysicalSelection`.
    Selection,
    /// `*PhysicalProjection`.
    Projection,
    /// `*PhysicalLimit`.
    Limit,
    /// `*PhysicalSort`.
    Sort,
    /// `*PhysicalTopN`.
    TopN,
    /// `*PhysicalTableDual`.
    TableDual,
}

/// LogicalPlan is a tree of logical operators (`base.LogicalPlan`).
pub trait LogicalPlan: Any + Send {
    // ---- per-type boilerplate (M-IFACE / M-SELF), generated by logical_plan_boilerplate! ----

    /// The operator kind (`M-IFACE`).
    // glue: N1
    fn kind(&self) -> LogicalKind;
    /// For type assertions.
    // glue: N1
    fn as_any(&self) -> &dyn Any;
    /// For type assertions.
    // glue: N1
    fn as_any_mut(&mut self) -> &mut dyn Any;
    /// The embedded `BaseLogicalPlan`.
    // glue: N1 (Go struct embedding)
    fn base(&self) -> &BaseLogicalPlan;
    /// The embedded `BaseLogicalPlan`.
    // glue: N1 (Go struct embedding)
    fn base_mut(&mut self) -> &mut BaseLogicalPlan;
    /// The embedded `LogicalSchemaProducer`, for operators that embed one.
    // glue: N1 (Go struct embedding)
    fn schema_producer(&self) -> Option<&LogicalSchemaProducer> {
        None
    }
    /// The embedded `LogicalSchemaProducer`, for operators that embed one.
    // glue: N1 (Go struct embedding)
    fn schema_producer_mut(&mut self) -> Option<&mut LogicalSchemaProducer> {
        None
    }

    // ---- accessors of base.Plan / BaseLogicalPlan ----

    /// Go's plan id (`Plan.ID()`), not the arena index (N1 §3.6).
    // glue: accessor (Go baseimpl.Plan.ID; BaseLogicalPlan embeds baseimpl::Plan with D09.14 / VS1-23)
    fn id(&self) -> i32 {
        self.base().id
    }

    /// `Plan.TP()`.
    // glue: accessor (Go baseimpl.Plan.TP; BaseLogicalPlan embeds baseimpl::Plan with D09.14 / VS1-23)
    fn tp(&self) -> &'static str {
        self.base().tp
    }

    /// `BaseLogicalPlan.Children()`.
    // glue: accessor (Go BaseLogicalPlan.Children, ported with D09.14 / VS1-23)
    fn children(&self) -> &[PlanId] {
        &self.base().children
    }

    /// `p.Children()[i] = ...` (Go writes through the returned slice).
    // glue: accessor (Go BaseLogicalPlan.Children, ported with D09.14 / VS1-23)
    fn children_mut(&mut self) -> &mut [PlanId] {
        &mut self.base_mut().children
    }

    /// `BaseLogicalPlan.SetChildren`.
    // glue: accessor (Go BaseLogicalPlan.SetChildren, ported with D09.14 / VS1-23)
    fn set_children(&mut self, children: Vec<PlanId>) {
        self.base_mut().children = children;
    }

    /// `Schema()`: `BaseLogicalPlan` returns its child's schema, `LogicalSchemaProducer` its
    /// own (lazily cloned from the only child).
    // glue: accessor (Go BaseLogicalPlan.Schema / LogicalSchemaProducer.Schema, D09.14 / VS1-23)
    fn schema<'a>(&'a self, arena: &'a PlanArena) -> &'a Schema {
        match self.schema_producer() {
            Some(sp) => sp.schema(self.children(), arena),
            None => arena.get(self.children()[0]).schema(arena),
        }
    }

    /// `p.Schema()` for writing (Go writes through the returned `*Schema`): the own schema,
    /// or the child's for operators without one (N1 §3.3, `PlanArena::schema_mut`).
    // glue: accessor (Go BaseLogicalPlan.Schema / LogicalSchemaProducer.Schema, D09.14 / VS1-23)
    fn schema_mut<'a>(&'a mut self, arena: &'a mut PlanArena) -> &'a mut Schema {
        if self.schema_producer().is_some() {
            self.schema_producer()
                .expect("producer")
                .schema(self.children(), arena);
            return self
                .schema_producer_mut()
                .expect("producer")
                .schema_cell_mut();
        }
        let child = self.children()[0];
        arena.schema_mut(child)
    }

    /// A stand-in interface method for the pinned-idiom tests (`idiom_tests.rs`): the shape of
    /// `PredicatePushDown` (process the child, replace it with the returned root, write own
    /// fields, return `this` or a new root). Test builds only.
    #[cfg(test)]
    fn push_down(
        &mut self,
        ctx: &mut crate::PlanCtx<'_>,
        this: PlanId,
        predicates: Vec<String>,
    ) -> Result<PlanId, tidb_base::Error> {
        let _ = (ctx, predicates);
        Ok(this)
    }
}

/// PhysicalPlan is a tree of the physical operators (`base.PhysicalPlan`), shared as an
/// `Arc` tree from the start (N1 §3.4): `Send + Sync`, so a plan can go into the instance
/// plan cache and to executor workers as is.
///
/// Every operator embeds a [`BasePhysicalPlan`] (Go's struct embedding, `M-SELF`); the
/// per-type methods are generated by [`crate::physical_plan_boilerplate!`]. The default
/// methods are Go's promoted methods of `BasePhysicalPlan` / `baseimpl.Plan` (ported in
/// `physicalop/base_physical_plan.rs` and `baseimpl.rs`); an operator overrides the ones Go
/// overrides. `Attach2Task` comes with `base.Task` (D10.1, VS1-27).
pub trait PhysicalPlan: Any + Send + Sync {
    // ---- per-type boilerplate (M-IFACE / M-SELF), generated by physical_plan_boilerplate! ----

    /// The operator kind (`M-IFACE`).
    // glue: N1
    fn kind(&self) -> PhysicalKind;
    /// For type assertions.
    // glue: N1
    fn as_any(&self) -> &dyn Any;
    /// For type assertions.
    // glue: N1
    fn as_any_mut(&mut self) -> &mut dyn Any;
    /// The node as a trait object (Go's `p.Self`), for the default methods.
    // glue: M-SELF
    fn as_dyn(&self) -> &dyn PhysicalPlan;
    /// The embedded `BasePhysicalPlan`.
    // glue: N1 (Go struct embedding)
    fn base_physical(&self) -> &BasePhysicalPlan;
    /// The embedded `BasePhysicalPlan`.
    // glue: N1 (Go struct embedding)
    fn base_physical_mut(&mut self) -> &mut BasePhysicalPlan;
    /// A shallow copy of this node: fields copied, children and expressions shared. Replaces
    /// Go's generated deep `CloneForPlanCache` for path copying (N1 §3.5).
    // glue: N1 §3.5
    fn clone_node(&self) -> PhysicalPlanRef;

    // ---- base.Plan ----

    /// `Schema()`.
    // glue: dispatch (Go BasePhysicalPlan.Schema)
    fn schema(&self) -> &Schema {
        self.base_physical().schema()
    }
    /// `SetSchema()` of the operators that own a schema (`physicalSchemaProducer`).
    /// `BasePhysicalPlan` has none: Go has no such method on it.
    // glue: dispatch (Go physicalSchemaProducer.SetSchema, VS1-10)
    fn set_schema(&mut self, schema: Schema) {
        let _ = schema;
        panic!("{} has no schema of its own", self.tp());
    }
    /// Go's plan id (`Plan.ID()`).
    // glue: dispatch (Go baseimpl.Plan.ID)
    fn id(&self) -> i32 {
        self.base_physical().plan.id()
    }
    /// `SetID`.
    // glue: dispatch (Go baseimpl.Plan.SetID)
    fn set_id(&mut self, id: i32) {
        self.base_physical_mut().plan.set_id(id);
    }
    /// `TP()`.
    // glue: dispatch (Go baseimpl.Plan.TP)
    fn tp(&self) -> &'static str {
        self.base_physical().plan.tp()
    }
    /// `ExplainID()`; `sc` is the statement context of Go's stored `ctx` (`M-CTX`).
    // glue: dispatch (Go baseimpl.Plan.ExplainID)
    fn explain_id(&self, sc: Option<&StatementContext>) -> String {
        self.base_physical().plan.explain_id(sc)
    }
    /// `ExplainInfo()`.
    // glue: dispatch (Go BasePhysicalPlan.ExplainInfo)
    fn explain_info(&self) -> String {
        self.base_physical().explain_info()
    }
    /// `ReplaceExprColumns`.
    // glue: dispatch (Go baseimpl.Plan.ReplaceExprColumns)
    fn replace_expr_columns(&mut self, replace: &HashMap<String, Arc<Column>>) {
        self.base_physical_mut().plan.replace_expr_columns(replace);
    }
    /// `StatsInfo()`.
    // glue: dispatch (Go baseimpl.Plan.StatsInfo)
    fn stats_info(&self) -> Option<&Arc<StatsInfo>> {
        self.base_physical().plan.stats_info()
    }
    /// `OutputNames()`.
    // glue: dispatch (Go baseimpl.Plan.OutputNames)
    fn output_names(&self) -> NameSlice {
        self.base_physical().plan.output_names()
    }
    /// `SetOutputNames()`.
    // glue: dispatch (Go baseimpl.Plan.SetOutputNames)
    fn set_output_names(&mut self, names: NameSlice) {
        self.base_physical_mut().plan.set_output_names(names);
    }
    /// `QueryBlockOffset()`.
    // glue: dispatch (Go baseimpl.Plan.QueryBlockOffset)
    fn query_block_offset(&self) -> isize {
        self.base_physical().plan.query_block_offset()
    }
    /// `BuildPlanTrace()`.
    // glue: dispatch (Go BasePhysicalPlan.BuildPlanTrace)
    fn build_plan_trace(&self) -> PlanTrace {
        base_physical_plan::build_plan_trace(self.as_dyn())
    }
    /// `CloneForPlanCache()`; Go's `(nil, false)` is `None`.
    // glue: dispatch (Go baseimpl.Plan.CloneForPlanCache)
    fn clone_for_plan_cache(&self) -> Option<PhysicalPlanRef> {
        // baseimpl.Plan's answer, (nil, false), for any operator that does not override it.
        self.base_physical().plan.clone_for_plan_cache()?;
        None
    }

    // ---- base.PhysicalPlan ----

    /// `GetPlanCostVer1`.
    // glue: dispatch (Go BasePhysicalPlan.GetPlanCostVer1)
    fn get_plan_cost_ver1(
        &self,
        task_type: TaskType,
        option: &PlanCostOption,
    ) -> Result<f64, Error> {
        self.base_physical().get_plan_cost_ver1(task_type, option)
    }
    /// `GetPlanCostVer2`.
    // glue: dispatch (Go BasePhysicalPlan.GetPlanCostVer2)
    fn get_plan_cost_ver2(
        &self,
        task_type: TaskType,
        option: &PlanCostOption,
    ) -> Result<CostVer2, Error> {
        self.base_physical().get_plan_cost_ver2(task_type, option)
    }
    /// `ToPB`.
    // glue: dispatch (Go BasePhysicalPlan.ToPB)
    fn to_pb(&self, ctx: &BuildPBContext, store_type: StoreType) -> Result<tipb::Executor, Error> {
        self.base_physical().to_pb(ctx, store_type)
    }
    /// `GetChildReqProps`.
    // glue: dispatch (Go BasePhysicalPlan.GetChildReqProps)
    fn get_child_req_props(&self, idx: isize) -> Option<&Arc<PhysicalProperty>> {
        self.base_physical().get_child_req_props(idx)
    }
    /// `StatsCount`.
    // glue: dispatch (Go BasePhysicalPlan.StatsCount)
    fn stats_count(&self) -> f64 {
        self.base_physical().stats_count()
    }
    /// `ExtractCorrelatedCols`.
    // glue: dispatch (Go BasePhysicalPlan.ExtractCorrelatedCols)
    fn extract_correlated_cols(&self) -> Vec<Arc<CorrelatedColumn>> {
        self.base_physical().extract_correlated_cols()
    }
    /// `Children()`.
    // glue: dispatch (Go BasePhysicalPlan.Children)
    fn children(&self) -> &[PhysicalPlanRef] {
        self.base_physical().children()
    }
    /// `p.Children()[i] = ...`; use [`crate::map_children`] to rewrite children.
    // glue: accessor (Go writes through the slice BasePhysicalPlan.Children returns)
    fn children_mut(&mut self) -> &mut Vec<PhysicalPlanRef> {
        &mut self.base_physical_mut().children
    }
    /// `SetChildren`.
    // glue: dispatch (Go BasePhysicalPlan.SetChildren)
    fn set_children(&mut self, children: Vec<PhysicalPlanRef>) {
        self.base_physical_mut().set_children(children);
    }
    /// `SetChild`.
    // glue: dispatch (Go BasePhysicalPlan.SetChild)
    fn set_child(&mut self, i: isize, child: PhysicalPlanRef) {
        self.base_physical_mut().set_child(i, child);
    }
    /// `ResolveIndices`.
    // glue: dispatch (Go BasePhysicalPlan.ResolveIndices)
    fn resolve_indices(&mut self) -> Result<(), Error> {
        self.base_physical_mut().resolve_indices()
    }
    /// `SetStats`.
    // glue: dispatch (Go baseimpl.Plan.SetStats)
    fn set_stats(&mut self, s: Option<Arc<StatsInfo>>) {
        self.base_physical_mut().plan.set_stats(s);
    }
    /// `ExplainNormalizedInfo`.
    // glue: dispatch (Go BasePhysicalPlan.ExplainNormalizedInfo)
    fn explain_normalized_info(&self) -> String {
        self.base_physical().explain_normalized_info()
    }
    /// `Clone`.
    // glue: dispatch (Go BasePhysicalPlan.Clone)
    fn clone_plan(&self) -> Result<PhysicalPlanRef, Error> {
        base_physical_plan::clone_plan(self.as_dyn())
    }
    /// `AppendChildCandidate`.
    // glue: dispatch (Go BasePhysicalPlan.AppendChildCandidate)
    fn append_child_candidate(&self, op: &PhysicalOptimizeOp) {
        base_physical_plan::append_child_candidate(self.as_dyn(), op);
    }
    /// `MemoryUsage`.
    // glue: dispatch (Go BasePhysicalPlan.MemoryUsage)
    fn memory_usage(&self) -> i64 {
        self.base_physical().memory_usage()
    }
    /// `SetProbeParents`.
    // glue: dispatch (Go BasePhysicalPlan.SetProbeParents)
    fn set_probe_parents(&mut self, probe_parents: Vec<PhysicalPlanRef>) {
        self.base_physical_mut().set_probe_parents(probe_parents);
    }
    /// `GetEstRowCountForDisplay`.
    // glue: dispatch (Go BasePhysicalPlan.GetEstRowCountForDisplay)
    fn get_est_row_count_for_display(&self) -> f64 {
        self.base_physical().get_est_row_count_for_display()
    }
    /// `GetActualProbeCnt`.
    // glue: dispatch (Go BasePhysicalPlan.GetActualProbeCnt)
    fn get_actual_probe_cnt(&self, stats_coll: &RuntimeStatsColl) -> i64 {
        self.base_physical().get_actual_probe_cnt(stats_coll)
    }
}
