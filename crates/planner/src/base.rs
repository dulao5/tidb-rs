//! The plan interfaces of `pkg/planner/core/base/plan_base.go` in N1's representation.
//!
//! - `base.LogicalPlan` is the [`LogicalPlan`] trait. Nodes live in the [`PlanArena`] and
//!   refer to each other by [`PlanId`] (`M-PLAN`). Each Go interface method becomes a trait
//!   method `fn xxx(&mut self, ctx: &mut PlanCtx<'_>, this: PlanId, ...)` plus a dispatch
//!   function of the same name ([`crate::logical_dispatch!`]); `this` is the node's own id
//!   (Go's `return p` is `Ok(this)`).
//! - Go's `BaseLogicalPlan.self` back-pointer and struct embedding become trait default
//!   methods plus the accessors `base()` / `schema_producer()` (`M-SELF`, N1 §3.7), generated
//!   by [`crate::logical_plan_boilerplate!`].
//! - `base.PhysicalPlan` is the [`PhysicalPlan`] trait over `Arc` trees (N1 §3.4).
//!
//! Only the structural part is here; the Go methods are added with the operators and rules
//! that need them (VS1-19, VS1-23, VS1-27). The logical accessors below are glue until then: the Go
//! accessor functions (`Plan.ID`, `BaseLogicalPlan.Children`, ...) get their `// go:`
//! annotation when their block is ported.

